
CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_id INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day INTEGER NOT NULL,
    month INTEGER NOT NULL,
    year INTEGER NOT NULL,
    day_name VARCHAR(20),
    month_name VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS gold.dim_category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.dim_author (
    author_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS gold.fact_articles (
    article_id VARCHAR(64) PRIMARY KEY,
    date_id INTEGER NOT NULL REFERENCES gold.dim_date(date_id),
    category_id INTEGER NOT NULL REFERENCES gold.dim_category(category_id),
    author_id INTEGER REFERENCES gold.dim_author(author_id),
    published_hour SMALLINT NOT NULL
        CHECK (published_hour BETWEEN 0 AND 23),
    word_count INTEGER NOT NULL CHECK (word_count >= 0),
    article_count INTEGER NOT NULL DEFAULT 1
        CHECK (article_count = 1)
);
